CREATE SCHEMA IF NOT EXISTS ONCO_PHARMA_DATA.HUB;
CREATE SCHEMA IF NOT EXISTS ONCO_PHARMA_DATA.SP;
CREATE SCHEMA IF NOT EXISTS ONCO_PHARMA_DATA.IQVIA;

