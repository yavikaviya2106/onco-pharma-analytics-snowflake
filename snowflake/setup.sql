--Creating database for storing source data only
CREATE DATABASE IF NOT EXISTS ONCO_PHARMA_DATA;

-- Creating a file format 
CREATE FILE FORMAT IF NOT EXISTS 
    ONCO_PHARMA_DATA.PUBLIC.LOCAL_CSV_FORMAT 
        TYPE=CSV 
        FIELD_DELIMITER = ','
        RECORD_DELIMITER = '\n'
        SKIP_HEADER = 1
        FIELD_OPTIONALLY_ENCLOSED_BY='"' 
        NULL_IF=('NULL','') 
        EMPTY_FIELD_AS_NULL=TRUE
        ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

-- Creating an internal stage
CREATE STAGE IF NOT EXISTS
    ONCO_PHARMA_DATA.PUBLIC.LOCAL_CSV_STAGE
        FILE_FORMAT = (FORMAT_NAME = 'ONCO_PHARMA_DATA.PUBLIC.LOCAL_CSV_FORMAT')
    COMMENT = 'Internal stage for loading local CSV files into Snowflake source tables data';


--Creating source schemas
CREATE SCHEMA IF NOT EXISTS ONCO_PHARMA_DATA.PRODUCT_MDM;
