WITH journey AS (
    SELECT * FROM {{ ref('idl_ptnt_jrny') }}
),

journey_summary AS (
    SELECT
        patient_id,
        dim_prod_sk,
        MAX(product_id) AS product_id,
        CASE WHEN COUNT(DISTINCT dim_hcp_sk) = 1 THEN MAX(dim_hcp_sk) END AS dim_hcp_sk,
        CASE WHEN COUNT(DISTINCT dim_hcp_sk) = 1 AND COUNT(DISTINCT hcp_npi) = 1 THEN MAX(hcp_npi) END AS hcp_npi,
        COUNT(DISTINCT dim_hcp_sk) AS associated_hcp_count,
        CASE WHEN COUNT(DISTINCT patient_age) = 1 THEN MAX(patient_age) END AS patient_age,
        CASE WHEN COUNT(DISTINCT gender) = 1 THEN MAX(gender) END AS gender,
        BOOLOR_AGG(COALESCE(hub_patient_flag, FALSE)) AS hub_patient_flag,
        BOOLOR_AGG(COALESCE(hub_enrolled_flag, FALSE)) AS hub_enrolled_flag,
        BOOLOR_AGG(COALESCE(bv_required_flag, FALSE)) AS bv_required_flag,
        BOOLOR_AGG(COALESCE(bv_completed_flag, FALSE)) AS bv_completed_flag,
        BOOLOR_AGG(COALESCE(coverage_confirmed_flag, FALSE)) AS coverage_confirmed_flag,
        BOOLOR_AGG(COALESCE(hub_pa_required_flag, FALSE)) AS hub_pa_required_flag,
        BOOLOR_AGG(COALESCE(hub_pa_submitted_flag, FALSE)) AS hub_pa_submitted_flag,
        BOOLOR_AGG(COALESCE(hub_pa_approved_flag, FALSE)) AS hub_pa_approved_flag,
        BOOLOR_AGG(COALESCE(hub_pa_denied_flag, FALSE)) AS hub_pa_denied_flag,
        BOOLOR_AGG(COALESCE(hub_pa_pending_flag, FALSE)) AS hub_pa_pending_flag,
        BOOLOR_AGG(COALESCE(pap_eligible_flag, FALSE)) AS pap_eligible_flag,
        BOOLOR_AGG(COALESCE(pap_enrolled_flag, FALSE)) AS pap_enrolled_flag,
        BOOLOR_AGG(COALESCE(pap_approved_flag, FALSE)) AS pap_approved_flag,
        BOOLOR_AGG(COALESCE(sp_referred_flag, FALSE)) AS sp_referred_flag,
        BOOLOR_AGG(COALESCE(sp_enrolled_flag, FALSE)) AS sp_enrolled_flag,
        BOOLOR_AGG(COALESCE(sp_pa_required_flag, FALSE)) AS sp_pa_required_flag,
        BOOLOR_AGG(COALESCE(sp_pa_submitted_flag, FALSE)) AS sp_pa_submitted_flag,
        BOOLOR_AGG(COALESCE(sp_pa_approved_flag, FALSE)) AS sp_pa_approved_flag,
        BOOLOR_AGG(COALESCE(sp_pa_denied_flag, FALSE)) AS sp_pa_denied_flag,
        BOOLOR_AGG(COALESCE(sp_pa_pending_flag, FALSE)) AS sp_pa_pending_flag,
        BOOLOR_AGG(COALESCE(hub_to_sp_flag, FALSE)) AS hub_to_sp_flag,
        BOOLOR_AGG(COALESCE(therapy_started_flag, FALSE)) AS therapy_started_flag,
        BOOLOR_AGG(COALESCE(pap_patient_flag, FALSE)) AS pap_patient_flag,
        BOOLOR_AGG(COALESCE(commercial_patient_flag, FALSE)) AS commercial_patient_flag,
        BOOLOR_AGG(COALESCE(pap_to_commercial_flag, FALSE)) AS pap_to_commercial_flag,
        MIN(first_observed_date) AS first_observed_date,
        MIN(first_hub_referral_date) AS first_hub_referral_date,
        MIN(first_hub_enrollment_date) AS first_hub_enrollment_date,
        MIN(first_hub_pa_submission_date) AS first_hub_pa_submission_date,
        MIN(first_hub_pa_decision_date) AS first_hub_pa_decision_date,
        MIN(first_pap_enrollment_date) AS first_pap_enrollment_date,
        MIN(first_pap_approval_date) AS first_pap_approval_date,
        MIN(first_sp_referral_date) AS first_sp_referral_date,
        MIN(first_sp_enrollment_date) AS first_sp_enrollment_date,
        MIN(first_sp_pa_submission_date) AS first_sp_pa_submission_date,
        MIN(first_sp_pa_decision_date) AS first_sp_pa_decision_date,
        MIN(therapy_start_date) AS therapy_start_date,
        MIN(first_dispense_date) AS first_dispense_date,
        MIN(first_sp_dispense_date) AS first_sp_dispense_date,
        MIN(first_pap_dispense_date) AS first_pap_dispense_date,
        MIN(pap_to_commercial_date) AS pap_to_commercial_date,
        MAX(last_dispense_date) AS last_dispense_date,
        MAX(last_sp_dispense_date) AS last_sp_dispense_date,
        MAX(last_pap_dispense_date) AS last_pap_dispense_date
    FROM journey
    GROUP BY patient_id, dim_prod_sk
),

journey_derived AS (
    SELECT
        *,
        CASE WHEN first_hub_pa_submission_date IS NOT NULL AND first_hub_pa_decision_date >= first_hub_pa_submission_date THEN DATEDIFF(DAY, first_hub_pa_submission_date, first_hub_pa_decision_date) END AS hub_pa_decision_days,
        CASE WHEN first_sp_pa_submission_date IS NOT NULL AND first_sp_pa_decision_date >= first_sp_pa_submission_date THEN DATEDIFF(DAY, first_sp_pa_submission_date, first_sp_pa_decision_date) END AS sp_pa_decision_days,
        CASE WHEN first_hub_referral_date IS NOT NULL AND first_sp_referral_date >= first_hub_referral_date THEN DATEDIFF(DAY, first_hub_referral_date, first_sp_referral_date) END AS hub_to_sp_transition_days,
        CASE WHEN first_pap_dispense_date IS NOT NULL AND first_sp_dispense_date > first_pap_dispense_date THEN DATEDIFF(DAY, first_pap_dispense_date, first_sp_dispense_date) END AS pap_to_commercial_days,
        CASE WHEN first_pap_dispense_date IS NOT NULL AND last_pap_dispense_date >= first_pap_dispense_date THEN DATEDIFF(DAY, first_pap_dispense_date, last_pap_dispense_date) + 1 END AS pap_duration_days,
        CASE WHEN first_hub_referral_date IS NOT NULL AND first_dispense_date >= first_hub_referral_date THEN DATEDIFF(DAY, first_hub_referral_date, first_dispense_date) END AS time_to_therapy_days
    FROM journey_summary
),

fill_summary AS (
    SELECT
        patient_id,
        dim_prod_sk,
        COUNT(*) AS total_fills,
        COALESCE(COUNT_IF(unit_source = 'SP'), 0) AS total_sp_fills,
        COALESCE(COUNT_IF(unit_source = 'PAP'), 0) AS total_pap_fills,
        COALESCE(COUNT_IF(refill_flag), 0) AS refill_count,
        COALESCE(COUNT_IF(unit_source = 'SP' AND channel_refill_flag), 0) AS sp_channel_refill_count,
        COALESCE(COUNT_IF(unit_source = 'PAP' AND channel_refill_flag), 0) AS pap_channel_refill_count,
        MIN(fill_date) AS first_fill_date,
        MAX(fill_date) AS latest_fill_date,
        MIN(CASE WHEN unit_source = 'SP' THEN fill_date END) AS first_sp_fill_date,
        MAX(CASE WHEN unit_source = 'SP' THEN fill_date END) AS latest_sp_fill_date,
        MIN(CASE WHEN unit_source = 'PAP' THEN fill_date END) AS first_pap_fill_date,
        MAX(CASE WHEN unit_source = 'PAP' THEN fill_date END) AS latest_pap_fill_date,
        SUM(quantity_dispensed) AS total_dispensed_units,
        SUM(CASE WHEN unit_source = 'SP' THEN quantity_dispensed ELSE 0 END) AS total_sp_units,
        SUM(CASE WHEN unit_source = 'PAP' THEN quantity_dispensed ELSE 0 END) AS total_pap_units,
        SUM(days_supply) AS total_days_supply,
        SUM(CASE WHEN unit_source = 'SP' THEN days_supply ELSE 0 END) AS total_sp_days_supply,
        SUM(CASE WHEN unit_source = 'PAP' THEN days_supply ELSE 0 END) AS total_pap_days_supply,
        SUM(COALESCE(therapy_gap_days, 0)) AS total_gap_days,
        MAX(COALESCE(therapy_gap_days, 0)) AS max_gap_days,
        COALESCE(COUNT_IF(gap_30_flag), 0) AS gap_30_count,
        COALESCE(COUNT_IF(gap_60_flag), 0) AS gap_60_count,
        COALESCE(COUNT_IF(gap_90_flag), 0) AS gap_90_count,
        MAX(coverage_end_date) AS latest_coverage_end_date,
        MAX(CASE WHEN unit_source = 'SP' THEN coverage_end_date END) AS latest_sp_coverage_end_date,
        MAX(CASE WHEN unit_source = 'PAP' THEN coverage_end_date END) AS latest_pap_coverage_end_date
    FROM {{ ref('int_ptnt_fills') }}
    GROUP BY patient_id, dim_prod_sk
),

therapy_summary AS (
    SELECT * FROM {{ ref('int_ptnt_therapy') }}
)

SELECT
    j.patient_id                                               AS patient_id,
    j.dim_prod_sk                                              AS dim_prod_sk,
    j.product_id                                               AS product_id,
    j.dim_hcp_sk                                               AS dim_hcp_sk,
    j.hcp_npi                                                  AS hcp_npi,
    j.associated_hcp_count                                     AS associated_hcp_count,
    j.patient_age                                              AS patient_age,
    j.gender                                                   AS gender,
    j.hub_patient_flag                                         AS hub_patient_flag,
    j.hub_enrolled_flag                                        AS hub_enrolled_flag,
    j.bv_required_flag                                         AS bv_required_flag,
    j.bv_completed_flag                                        AS bv_completed_flag,
    j.coverage_confirmed_flag                                  AS coverage_confirmed_flag,
    j.hub_pa_required_flag                                     AS hub_pa_required_flag,
    j.hub_pa_submitted_flag                                    AS hub_pa_submitted_flag,
    j.hub_pa_approved_flag                                     AS hub_pa_approved_flag,
    j.hub_pa_denied_flag                                       AS hub_pa_denied_flag,
    j.hub_pa_pending_flag                                      AS hub_pa_pending_flag,
    j.pap_eligible_flag                                        AS pap_eligible_flag,
    j.pap_enrolled_flag                                        AS pap_enrolled_flag,
    j.pap_approved_flag                                        AS pap_approved_flag,
    j.sp_referred_flag                                         AS sp_referred_flag,
    j.sp_enrolled_flag                                         AS sp_enrolled_flag,
    j.sp_pa_required_flag                                      AS sp_pa_required_flag,
    j.sp_pa_submitted_flag                                     AS sp_pa_submitted_flag,
    j.sp_pa_approved_flag                                      AS sp_pa_approved_flag,
    j.sp_pa_denied_flag                                        AS sp_pa_denied_flag,
    j.sp_pa_pending_flag                                       AS sp_pa_pending_flag,
    j.hub_to_sp_flag                                           AS hub_to_sp_flag,
    j.therapy_started_flag                                     AS therapy_started_flag,
    j.pap_patient_flag                                         AS pap_patient_flag,
    j.commercial_patient_flag                                  AS commercial_patient_flag,
    j.pap_to_commercial_flag                                   AS pap_to_commercial_flag,
    j.first_observed_date                                      AS first_observed_date,
    j.first_hub_referral_date                                  AS first_hub_referral_date,
    j.first_hub_enrollment_date                                AS first_hub_enrollment_date,
    j.first_hub_pa_submission_date                             AS first_hub_pa_submission_date,
    j.first_hub_pa_decision_date                               AS first_hub_pa_decision_date,
    j.first_pap_enrollment_date                                AS first_pap_enrollment_date,
    j.first_pap_approval_date                                  AS first_pap_approval_date,
    j.first_sp_referral_date                                   AS first_sp_referral_date,
    j.first_sp_enrollment_date                                 AS first_sp_enrollment_date,
    j.first_sp_pa_submission_date                              AS first_sp_pa_submission_date,
    j.first_sp_pa_decision_date                                AS first_sp_pa_decision_date,
    j.therapy_start_date                                       AS therapy_start_date,
    j.first_dispense_date                                      AS first_dispense_date,
    j.first_sp_dispense_date                                   AS first_sp_dispense_date,
    j.first_pap_dispense_date                                  AS first_pap_dispense_date,
    j.pap_to_commercial_date                                   AS pap_to_commercial_date,
    j.last_dispense_date                                       AS last_dispense_date,
    j.last_sp_dispense_date                                    AS last_sp_dispense_date,
    j.last_pap_dispense_date                                   AS last_pap_dispense_date,
    j.hub_pa_decision_days                                     AS hub_pa_decision_days,
    j.sp_pa_decision_days                                      AS sp_pa_decision_days,
    j.hub_to_sp_transition_days                                AS hub_to_sp_transition_days,
    j.pap_to_commercial_days                                   AS pap_to_commercial_days,
    j.pap_duration_days                                        AS pap_duration_days,
    j.time_to_therapy_days                                     AS time_to_therapy_days,
    COALESCE(f.total_fills, 0)                                 AS total_fills,
    COALESCE(f.total_sp_fills, 0)                              AS total_sp_fills,
    COALESCE(f.total_pap_fills, 0)                             AS total_pap_fills,
    COALESCE(f.refill_count, 0)                                AS refill_count,
    COALESCE(f.sp_channel_refill_count, 0)                     AS sp_channel_refill_count,
    COALESCE(f.pap_channel_refill_count, 0)                    AS pap_channel_refill_count,
    f.first_fill_date                                          AS first_fill_date,
    f.latest_fill_date                                         AS latest_fill_date,
    f.first_sp_fill_date                                       AS first_sp_fill_date,
    f.latest_sp_fill_date                                      AS latest_sp_fill_date,
    f.first_pap_fill_date                                      AS first_pap_fill_date,
    f.latest_pap_fill_date                                     AS latest_pap_fill_date,
    COALESCE(f.total_dispensed_units, 0)                       AS total_dispensed_units,
    COALESCE(f.total_sp_units, 0)                              AS total_sp_units,
    COALESCE(f.total_pap_units, 0)                             AS total_pap_units,
    COALESCE(f.total_days_supply, 0)                           AS total_days_supply,
    COALESCE(f.total_sp_days_supply, 0)                        AS total_sp_days_supply,
    COALESCE(f.total_pap_days_supply, 0)                       AS total_pap_days_supply,
    COALESCE(f.total_gap_days, 0)                              AS total_gap_days,
    COALESCE(f.max_gap_days, 0)                                AS max_gap_days,
    COALESCE(f.gap_30_count, 0)                                AS gap_30_count,
    COALESCE(f.gap_60_count, 0)                                AS gap_60_count,
    COALESCE(f.gap_90_count, 0)                                AS gap_90_count,
    f.latest_coverage_end_date                                 AS latest_coverage_end_date,
    f.latest_sp_coverage_end_date                              AS latest_sp_coverage_end_date,
    f.latest_pap_coverage_end_date                             AS latest_pap_coverage_end_date,
     t.data_as_of_date                                          AS data_as_of_date,
    t.last_coverage_end_date                                   AS last_coverage_end_date,
    t.therapy_episode_count                                    AS therapy_episode_count,
    t.first_restart_date                                       AS first_restart_date,
    t.discontinuation_date                                     AS discontinuation_date,
    t.latest_discontinuation_date                              AS latest_discontinuation_date,
    COALESCE(t.current_explicit_discontinued_flag, FALSE)      AS current_explicit_discontinued_flag,
    t.therapy_status                                           AS therapy_status,
    t.days_on_therapy                                          AS days_on_therapy,
    t.days_to_discontinuation                                  AS days_to_discontinuation,
    t.total_patient_flag                                       AS total_patient_flag,
    t.new_patient_flag                                         AS new_patient_flag,
    t.active_patient_flag                                      AS active_patient_flag,
    t.inactive_patient_flag                                    AS inactive_patient_flag,
    t.discontinued_patient_flag                                AS discontinued_patient_flag,
    t.restarted_patient_flag                                   AS restarted_patient_flag,
    t.therapy_started_flag                                     AS therapy_started_therapy_flag,
    t.persistent_30_flag                                       AS persistent_30_flag,
    t.persistent_90_flag                                       AS persistent_90_flag,
    t.persistent_180_flag                                      AS persistent_180_flag,
    t.persistent_365_flag                                      AS persistent_365_flag
FROM journey_derived j
LEFT JOIN fill_summary f
    ON j.patient_id = f.patient_id
    AND j.dim_prod_sk = f.dim_prod_sk
LEFT JOIN therapy_summary t
    ON j.patient_id = t.patient_id
    AND j.dim_prod_sk = t.dim_prod_sk
